package org.swetlokognatsk.earking_out.core.ports.identity;

import org.swetlokognatsk.earking_out.core.domain.model.identity.UserAggregate;
import org.swetlokognatsk.earking_out.core.domain.model.identity.UserId;
import org.swetlokognatsk.earking_out.core.domain.model.identity.oauth.OauthIdentity;
import org.swetlokognatsk.earking_out.core.domain.model.identity.oauth.OauthProviders;
import org.swetlokognatsk.earking_out.core.ports.base.TypedAggregateRepository;

public interface UserRepository extends TypedAggregateRepository<UserId, UserAggregate> {
    /** the full name of user will be namePrefix + userId */
    UserAggregate createAndSaveGuestUser(String namePrefix);

    // this is entity-creating method, so it's conducted not via standard `repository.save(repository.getAggregate().doSomething())` flow - because id of new OauthIdentity is generated by storage
    void attachOauthIdentity(UserId userId, OauthProviders provider, String providerUserId, String userName, String pictureUrl);

    boolean hasOauthIdentity(OauthProviders provider, String providerUserId);

    // TODO ddd violation - obtaining the raw entity via aggregate
    OauthIdentity getOauthIdentity(OauthProviders provider, String providerUserId);
}
